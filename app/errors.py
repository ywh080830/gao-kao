# -*- coding: utf-8 -*-
"""统一错误码定义与带码错误信息生成。

设计要点：
- 所有面向用户的错误提示都带一个稳定错误码（如 DL001），方便用户在帮助页 / 日志中
  快速定位原因，也便于排查（日志里搜索错误码即可）。
- 错误码前缀含义：DL=数据下载、DB=本地数据库、CF=配置、IO=文件读写、UN=未知。
"""
# 错误码 -> (简短标题, 处理建议)
ERROR_CODES = {
    "DL001": ("云端下载失败", "检查网络连接后重试；下载依赖网络可达，离线环境无法获取数据。"),
    "DL002": ("数据完整性校验失败", "下载的文件与数据源不一致，建议先「清除已下载数据」再重新下载。"),
    "DL003": ("无法获取数据源清单", "无法连接数据源，请检查网络后点击「检查更新」或稍后重试。"),
    "DB001": ("本地数据库打开失败", "本地数据库可能损坏，建议「清除已下载数据」后重新下载。"),
    "DB002": ("本地数据库缺失", "尚未下载本地数据，请联网后到「数据管理」点击「下载全部到本地」。"),
    "CF001": ("用户配置读取失败", "用户配置文件损坏，已自动恢复默认设置。"),
    "IO001": ("文件写入失败", "保存位置不可写，请检查目录权限或更换保存位置。"),
    "UN001": ("未知错误", "发生了未预期的错误，请将日志文件（保存目录/userdata/app.log）反馈以便排查。"),
}


def code_info(code: str):
    return ERROR_CODES.get(code, ("未知错误", ""))


def fmt(code: str, detail: str = "") -> str:
    """生成带错误码的用户提示文本（用于弹窗 / 状态栏）。

    形如：
        [DL001] 云端下载失败
        <detail 若存在>
        检查网络连接后重试；下载依赖网络可达…
    """
    title, suggest = code_info(code)
    lines = ["[%s] %s" % (code, title)]
    if detail:
        lines.append(detail)
    if suggest:
        lines.append(suggest)
    return "\n".join(lines)
